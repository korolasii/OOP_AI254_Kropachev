package pixelbattle.core;

/**
 * Ультимейт — найсильніше вміння, як у Dota 2.
 * Стає доступним, коли енергія бійця досягає 100.
 * Діє одразу на всіх: allies — союзники (включно з собою), enemies — вороги.
 *
 * У інтерфейсі ТРИ методи — тому лямбдою його не записати.
 * Реалізуйте його анонімним класом або звичайним класом.
 */
public interface Ultimate {

    /** Назва ультимейту (показується на кнопці). */
    String getName();

    /** Короткий опис (підказка при наведенні миші на кнопку). */
    String getDescription();

    /** Що робить ультимейт. Повертає рядок для журналу бою. */
    String activate(Fighter user, Fighter[] allies, Fighter[] enemies);
}
